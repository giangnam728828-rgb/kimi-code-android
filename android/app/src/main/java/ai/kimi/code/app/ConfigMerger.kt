package ai.kimi.code.app

/**
 * Pure (Android-free) TOML text surgery for `~/.kimi-code/config.toml`.
 *
 * The launcher used to call `file.writeText()` on every proot start, replacing
 * the whole file with App-generated providers/models. Anything the server wrote
 * into the same file -- the OAuth credential from a Kimi sign-in, thinking
 * effort defaults, or models added from inside the workspace -- was erased on
 * the next restart. Users saw it as "I added a model, the app restarted, and I
 * was logged out with my chats gone".
 *
 * The App now owns only a marked block plus the top-level `default_model` key.
 * Everything else is preserved byte-for-byte. Kept free of Android types so the
 * behaviour is covered by plain JVM unit tests.
 */
object ConfigMerger {

    const val MANAGED_START = "# >>> kimi-code-android managed:start"
    const val MANAGED_END = "# <<< kimi-code-android managed:end"
    const val LEGACY_MARKER = "# Generated by the Kimi Code Android app"

    private val SECTION_HEADER = Regex("^\\s*\\[{1,2}\\s*([^\\]]+?)\\s*\\]{1,2}\\s*(?:#.*)?$")
    private val DEFAULT_MODEL_LINE = Regex("^\\s*default_model\\s*=")
    private val BARE_KEY = Regex("[A-Za-z0-9_-]+(\\.[A-Za-z0-9_-]+)*")

    /** Escape a value for a TOML basic string. */
    fun escape(value: String): String {
        val out = StringBuilder(value.length + 8)
        for (ch in value) {
            when (ch) {
                '\\' -> out.append("\\\\")
                '"' -> out.append("\\\"")
                '\n' -> out.append("\\n")
                '\r' -> out.append("\\r")
                '\t' -> out.append("\\t")
                '\b' -> out.append("\\b")
                else -> if (ch.code < 0x20) {
                    out.append("\\u").append(ch.code.toString(16).padStart(4, '0'))
                } else {
                    out.append(ch)
                }
            }
        }
        return out.toString()
    }

    /** Quote a TOML key only when it is not a bare dotted key. */
    fun quoteKey(value: String): String =
        if (BARE_KEY.matches(value)) value else "\"${escape(value)}\""

    /**
     * Lines describing a model's thinking-effort preference.
     *
     * Deliberately emits ONLY `default_effort`, never `support_efforts` or
     * `off_effort`. Those two are *capability metadata*: declaring
     * `support_efforts` makes the server treat the model as "reasons by
     * default", and it then rejects any request with `effort = 'off'` unless an
     * `off_effort` is also declared (kimi-code `thinking.ts`, error
     * `off-needs-offeffort`). For user-supplied custom endpoints we cannot know
     * which wire value actually disables reasoning -- sending e.g. "none" can
     * make the upstream API return 400. With no capability metadata the server
     * falls back to `encode: 'silent'`, i.e. it simply omits the effort field,
     * which is safe for every OpenAI-compatible endpoint.
     *
     * `default_effort` is a user preference, not a capability claim, so it is
     * safe to write and still lets the chosen low/medium/high level take effect.
     */
    fun effortLines(effort: String): String =
        if (effort.isBlank()) "" else "default_effort = \"${escape(effort)}\"\n"

    /** Section names present in a fragment of TOML text. */
    fun sectionNames(text: String): Set<String> = text.lineSequence()
        .mapNotNull { SECTION_HEADER.matchEntire(it)?.groupValues?.get(1)?.trim() }
        .toSet()

    private data class Block(val header: String?, val lines: MutableList<String> = mutableListOf())

    private fun splitBlocks(lines: List<String>): MutableList<Block> {
        val blocks = mutableListOf(Block(null))
        for (line in lines) {
            val header = SECTION_HEADER.matchEntire(line)?.groupValues?.get(1)?.trim()
            if (header != null) {
                blocks.add(Block(header, mutableListOf(line)))
            } else {
                blocks.last().lines.add(line)
            }
        }
        return blocks
    }

    /**
     * Merge the App-owned sections into [existing], preserving every other line.
     *
     * @param existing     current file content, or "" when the file is absent
     * @param managedBlock App-generated `[providers.*]` / `[models.*]` sections
     *                     (without the marker comments)
     * @param defaultModel the App-selected default model alias (a top-level key)
     */
    fun merge(existing: String, managedBlock: String, defaultModel: String): String {
        val owned = sectionNames(managedBlock)
        val managed = managedBlock.trimEnd('\n')

        if (existing.isBlank()) return compose(emptyList(), managed, defaultModel)

        val original = existing.lines()
        val hasMarker = original.any { it.trim() == MANAGED_START }

        // Pre-marker versions rewrote the whole file on every launch, so their
        // files have no managed block. Drop only the sections those versions
        // generated (otherwise they would collide with the new ones as
        // duplicate TOML keys) and keep anything else -- a hand-added [auth]
        // block with a login credential is worth preserving on upgrade.
        val legacyOnly = !hasMarker && original.firstOrNull()?.trim() == LEGACY_MARKER

        val keptLines = if (legacyOnly) stripLegacyAppSections(original) else stripManagedBlock(original)
        val blocks = splitBlocks(keptLines)

        // Drop only the sections the App is about to write again. Sections with
        // other names -- including models the user added inside the workspace --
        // are left untouched.
        blocks.removeAll { it.header != null && it.header in owned }

        // `default_model` is a top-level key: remove any previous one from the
        // top-level block so we never emit a duplicate TOML key.
        blocks.first().lines.removeAll { DEFAULT_MODEL_LINE.containsMatchIn(it) }

        return compose(blocks.map { it.lines }, managed, defaultModel)
    }

    /**
     * Remove only the App-owned block, keeping every other line intact. Used
     * when the user clears App-managed models: the login credential and any
     * workspace-authored config must survive.
     */
    fun removeManaged(existing: String): String {
        if (existing.isBlank()) return ""
        val original = existing.lines()
        val legacyOnly = !original.any { it.trim() == MANAGED_START } &&
            original.firstOrNull()?.trim() == LEGACY_MARKER
        if (legacyOnly) return ""
        val kept = stripManagedBlock(original)
        val blocks = splitBlocks(kept)
        blocks.first().lines.removeAll { DEFAULT_MODEL_LINE.containsMatchIn(it) }
        return blocks.flatMap { it.lines }.joinToString("\n").trimEnd('\n') + "\n"
    }

    private fun stripManagedBlock(lines: List<String>): List<String> {
        val out = mutableListOf<String>()
        var inside = false
        for (line in lines) {
            when {
                line.trim() == MANAGED_START -> inside = true
                line.trim() == MANAGED_END -> inside = false
                inside -> Unit
                else -> out.add(line)
            }
        }
        return out
    }

    /**
     * Legacy files were written whole by the app, so there is no marker to
     * delimit them. Keep every line that is not part of an App-generated
     * `default_model` / `[providers.*]` / `[models.*]` block. An `[auth]` block
     * someone added by hand (or that a newer server wrote) survives the upgrade.
     */
    private fun stripLegacyAppSections(lines: List<String>): List<String> {
        val blocks = splitBlocks(lines)
        val top = blocks.first()
        top.lines.removeAll { it.trim() == LEGACY_MARKER || DEFAULT_MODEL_LINE.containsMatchIn(it) }
        blocks.removeAll { block ->
            val header = block.header ?: return@removeAll false
            header == "providers" || header.startsWith("providers.") ||
                header == "models" || header.startsWith("models.")
        }
        return blocks.flatMap { it.lines }
    }

    private fun compose(kept: List<List<String>>, managed: String, defaultModel: String): String {
        val out = mutableListOf<String>()

        val top = (kept.firstOrNull()?.toMutableList() ?: mutableListOf())
        while (top.lastOrNull()?.isBlank() == true) top.removeLast()
        if (top.isNotEmpty()) out.addAll(top)
        out.add("default_model = \"${escape(defaultModel)}\"")
        out.add("")

        kept.drop(1).forEach { lines ->
            val section = lines.toMutableList()
            while (section.lastOrNull()?.isBlank() == true) section.removeLast()
            if (section.isEmpty()) return@forEach
            out.addAll(section)
            out.add("")
        }

        out.add(MANAGED_START)
        if (managed.isNotBlank()) out.addAll(managed.lineSequence().toList())
        out.add(MANAGED_END)
        return out.joinToString("\n").trimEnd('\n') + "\n"
    }
}
