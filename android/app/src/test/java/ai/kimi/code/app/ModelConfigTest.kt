package ai.kimi.code.app

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * 回归测试：2.15.0 在同一分组内切换模型后报
 * `Model "custom-2/deepseek-v4.1-flash" is not configured in config.toml.`。
 *
 * 这里把「网页下拉能选到的 key」与「config 里存在的 [models.*] 段」当作
 * 同一个集合来验证：切换默认模型不得让任何已有段消失。
 */
class ModelConfigTest {

    private fun section(key: String, model: String, extra: String = ""): String = buildString {
        appendLine("[models.${ConfigMerger.quoteKey(key)}]")
        appendLine("provider = \"${key.substringBefore('/')}\"")
        appendLine("model = \"$model\"")
        appendLine("max_context_size = 131072")
        if (extra.isNotBlank()) appendLine(extra)
        appendLine()
    }

    private fun config(vararg sections: String, defaultModel: String = "custom-2/glm-5"): String =
        buildString {
            appendLine("# generated by kimi-code-android")
            appendLine("default_model = \"$defaultModel\"")
            appendLine()
            appendLine(ConfigMerger.MANAGED_START)
            sections.forEach { append(it) }
            appendLine(ConfigMerger.MANAGED_END)
        }

    @Test
    fun `reads quoted and bare model section keys`() {
        val text = config(
            section("custom-2/deepseek-v4.1-flash", "deepseek-v4.1-flash"),
            section("custom/glm-5", "glm-5"),
        )
        val keys = ModelConfig.modelKeys(text)
        assertTrue(keys.contains("custom-2/deepseek-v4.1-flash"))
        assertTrue(keys.contains("custom/glm-5"))
        assertEquals(2, keys.size)
    }

    @Test
    fun `preservedSections keeps every historical model not regenerated`() {
        val old = config(
            section("custom-2/deepseek-v4.1-flash", "deepseek-v4.1-flash", "support_efforts = [\"low\"]"),
            section("custom-2/glm-5", "glm-5"),
            section("custom/qwen-max", "qwen-max"),
        )
        val generated = setOf("custom-2/glm-5")
        val preserved = ModelConfig.preservedSections(old, generated)

        // 两个历史段都要回来，且服务端写入的能力元数据不能丢。
        assertTrue(preserved.contains("custom-2/deepseek-v4.1-flash"))
        assertTrue(preserved.contains("support_efforts"))
        assertTrue(preserved.contains("custom/qwen-max"))
        assertFalse(preserved.contains("[models.\"custom-2/glm-5\"]"))
    }

    @Test
    fun `switching default model never drops a section`() {
        // 用户场景：分组 custom-2 里有两个模型，从 glm-5 切到 deepseek-v4.1-flash。
        val old = config(
            section("custom-2/glm-5", "glm-5"),
            section("custom-2/deepseek-v4.1-flash", "deepseek-v4.1-flash"),
            defaultModel = "custom-2/glm-5",
        )
        val before = ModelConfig.modelKeys(old)
        val switched = ModelConfig.withDefaultModel(old, "custom-2/deepseek-v4.1-flash")
        val after = ModelConfig.modelKeys(switched)

        assertEquals("切换默认模型不得增删任何模型段", before, after)
        assertTrue(switched.contains("default_model = \"custom-2/deepseek-v4.1-flash\""))
        assertFalse(switched.contains("default_model = \"custom-2/glm-5\""))
        // 目标模型仍然可解析，发消息不会再报 is not configured。
        assertTrue(after.contains("custom-2/deepseek-v4.1-flash"))
    }

    @Test
    fun `withDefaultModel keeps everything else byte identical`() {
        val old = config(section("custom-2/glm-5", "glm-5"), defaultModel = "custom-2/glm-5")
        val switched = ModelConfig.withDefaultModel(old, "custom-2/glm-5")
        assertEquals("指向同一个模型时不应改动文件", old, switched)
    }

    @Test
    fun `healMissingSection repairs the exact reported failure`() {
        // 2.15.0 删段后留下的状态：default_model 指向的 key 没有段。
        val broken = buildString {
            appendLine("default_model = \"custom-2/deepseek-v4.1-flash\"")
            appendLine(ConfigMerger.MANAGED_START)
            appendLine("[providers.custom-2]")
            appendLine("type = \"openai\"")
            appendLine(ConfigMerger.MANAGED_END)
        }
        assertFalse(ModelConfig.modelKeys(broken).contains("custom-2/deepseek-v4.1-flash"))

        val healed = ModelConfig.healMissingSection(
            broken, "custom-2/deepseek-v4.1-flash", 131072,
        )
        assertTrue(healed.contains("[models.\"custom-2/deepseek-v4.1-flash\"]"))
        assertTrue(healed.contains("model = \"deepseek-v4.1-flash\""))
        assertTrue(healed.contains("provider = \"custom-2\""))
        assertTrue(ModelConfig.modelKeys(healed).contains("custom-2/deepseek-v4.1-flash"))
    }

    @Test
    fun `healMissingSection is a no-op when section already exists`() {
        val old = config(section("custom-2/glm-5", "glm-5"))
        assertEquals("", ModelConfig.healMissingSection(old, "custom-2/glm-5", 131072))
    }

    @Test
    fun `idsFor lists models belonging to one group only`() {
        val text = config(
            section("custom-2/glm-5", "glm-5"),
            section("custom-2/deepseek-v4.1-flash", "deepseek-v4.1-flash"),
            section("openai/gpt-4o", "gpt-4o"),
        )
        assertEquals(listOf("deepseek-v4.1-flash", "glm-5"), ModelConfig.idsFor(text, "custom-2"))
        assertEquals(listOf("gpt-4o"), ModelConfig.idsFor(text, "openai"))
    }

    @Test
    fun `renderSection output is parseable as a model section`() {
        val rendered = ModelConfig.renderSection(
            ModelConfig.Spec(
                key = "custom-2/deepseek-v4.1-flash",
                alias = "custom-2",
                modelId = "deepseek-v4.1-flash",
                contextSize = 131072,
                effort = "medium",
            ),
        )
        assertTrue(ModelConfig.modelKeys(rendered).contains("custom-2/deepseek-v4.1-flash"))
        assertTrue(rendered.contains("default_effort = \"medium\""))
    }

    @Test
    fun `full rebuild keeps historical keys from the web dropdown`() {
        // 模拟 write()：本次只生成 1 个模型，但旧 config 里还有 2 个历史段。
        val old = config(
            section("custom-2/glm-5", "glm-5"),
            section("custom-2/deepseek-v4.1-flash", "deepseek-v4.1-flash"),
            section("custom-2/qwen-plus", "qwen-plus"),
        )
        val generatedKeys = setOf("custom-2/glm-5")
        val preserved = ModelConfig.preservedSections(old, generatedKeys)
        val newManaged = ModelGroup.renderManaged(
            listOf(
                ModelGroup.Group(
                    alias = "custom-2", title = "custom-2", type = "openai",
                    baseUrl = "https://api.example.com/v1", apiKey = "sk-x",
                    defaultModel = "glm-5", models = listOf("glm-5"),
                    contextSize = 131072, effort = "", sourceIndex = 0,
                ),
            ),
        ) + "\n" + preserved
        val merged = ConfigMerger.merge(old, newManaged, "custom-2/deepseek-v4.1-flash")
        val keys = ModelConfig.modelKeys(merged)

        assertTrue(keys.contains("custom-2/glm-5"))
        assertTrue(keys.contains("custom-2/deepseek-v4.1-flash"))
        assertTrue(keys.contains("custom-2/qwen-plus"))
        assertTrue(merged.contains("default_model = \"custom-2/deepseek-v4.1-flash\""))
        // 每个段只出现一次，TOML 不允许重复 key。
        keys.forEach { key ->
            val header = "[models.${ConfigMerger.quoteKey(key)}]"
            assertEquals("$header 重复", 1, merged.split(header).size - 1)
        }
    }
}
